const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { createEditorHarness } = require('./editorHarness.cjs')

exports.run = async () => {
  const harness = await createEditorHarness('embeds')
  const outside = await fs.mkdtemp(path.join(os.tmpdir(), 'canofold-embed-outside-'))
  const html = '<!doctype html><style>body{color:navy}</style><h1>Local embed loaded</h1><script>throw new Error("MUST_NOT_EXECUTE")</script><p onclick="alert(1)">中文 English</p>'
  const source = (name, href) => `# Embed ${name}\n\n::embed[Test frame]{src="${href}" loading="eager"}`
  const frameReady = (name) => (s) => s.title === `Embed ${name}` && s.embeds.length === 1 && !s.embeds[0].busy && s.embeds[0].loaded
  const preview = async (name, href) => { await harness.edit(source(name, href)); return harness.wait(`iframe ${name}`, frameReady(name)) }
  const success = async (name, href) => {
    const result = await preview(name, href)
    assert.match(result.embeds[0].html, /Local embed loaded/)
    assert.doesNotMatch(result.embeds[0].html, /<script|onclick=/i)
    assert.equal(result.embeds[0].sandbox, '')
    return result
  }
  const failure = async (name, href, message) => {
    const result = await preview(name, href)
    assert.match(result.embeds[0].html, /Embedded document could not be loaded/)
    if (message) assert.match(result.embeds[0].html, message)
  }
  try {
    await fs.writeFile(path.join(harness.fixture, 'local.html'), html)
    await fs.mkdir(path.join(harness.fixture, 'public'))
    await fs.writeFile(path.join(harness.fixture, 'public', 'absolute.htm'), '\uFEFF'+html)
    await fs.writeFile(path.join(outside, 'outside.html'), '<p>OUTSIDE_SECRET_MUST_NOT_RENDER</p>')
    await fs.symlink(path.join(outside, 'outside.html'), path.join(harness.fixture, 'linked.html'))
    await fs.symlink(outside, path.join(harness.fixture, 'linked-directory'))
    await fs.writeFile(path.join(harness.fixture, 'too-large.html'), 'x'.repeat(2 * 1024 * 1024 + 1))
    await fs.writeFile(path.join(harness.fixture, 'invalid-utf8.html'), Buffer.from([0xc3, 0x28]))
    await fs.mkdir(path.join(harness.fixture, 'directory.html'))
    await fs.writeFile(path.join(harness.fixture, 'unsupported.txt'), html)
    await harness.edit(source('INITIAL', './local.html'))
    await harness.open()
    const initial = await harness.wait('iframe first real load', frameReady('INITIAL'))
    assert.match(initial.embeds[0].html, /Local embed loaded/)
    assert.deepEqual(initial.violations, [])
    await harness.edit('# Embed DEFAULT_LAZY\n\n::embed[Test frame]{src="./local.html"}')
    const lazy = await harness.wait('iframe default lazy loading in the viewport', frameReady('DEFAULT_LAZY'))
    assert.match(lazy.embeds[0].html, /Local embed loaded/)
    await fs.writeFile(path.join(harness.fixture, 'unsafe.html'), '<p>Local embed loaded</p><meta http-equiv="refresh" content="0;url=https://example.com"><base href="https://example.com/"><a href="java&#10;script:alert(1)">Unsafe link</a><img src="file:///secret.svg"><link rel="modulepreload" href="./script.js">')
    const unsafe = await success('UNSAFE_MARKUP', './unsafe.html')
    assert.doesNotMatch(unsafe.embeds[0].html, /http-equiv|<base|alert\(1\)|file:\/\/\/|modulepreload/i)
    await fs.writeFile(path.join(harness.fixture, 'image.svg'), '<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"><rect width="10" height="10" fill="green"/></svg>')
    await fs.copyFile(path.join(harness.fixture, 'image.svg'), path.join(harness.fixture, 'public', 'public-image.svg'))
    await fs.writeFile(path.join(harness.fixture, 'child.css'), 'body{background:url("./image.svg")}')
    await fs.writeFile(path.join(harness.fixture, 'style.css'), '@import "./child.css"; p{color:green}')
    await fs.writeFile(path.join(harness.fixture, 'resources.html'), '<!doctype html><link rel="stylesheet" href="./style.css"><style>p::after{content:"url(./literal)"}</style><p>Local embed loaded</p><img src="./image.svg"><img src="/public-image.svg">')
    const resources = await success('RESOURCES', './resources.html')
    assert.match(resources.embeds[0].html, /data:image\/svg\+xml;base64,/)
    assert.doesNotMatch(resources.embeds[0].html, /vscode-resource\.vscode-cdn\.net/)
    assert.match(resources.embeds[0].html, /url\(\.\/literal\)/)
    await fs.writeFile(path.join(harness.fixture, 'bad-resource.html'), '<p>Local embed loaded</p><img src="./missing.svg"><img src="./image.svg">')
    const bad = await success('BAD_RESOURCE', './bad-resource.html')
    assert.match(bad.embeds[0].html, /Embedded resources could not be loaded/)
    assert.match(bad.embeds[0].html, /data:image\/svg\+xml;base64,/)
    await fs.copyFile(path.join(harness.fixture, 'image.svg'), path.join(harness.fixture, 'missing.svg'))
    const assetRecovery = await success('RESOURCE_RECOVERY', './bad-resource.html')
    assert.doesNotMatch(assetRecovery.embeds[0].html, /Embedded resources could not be loaded/)
    await fs.writeFile(path.join(harness.fixture, 'cycle.css'), '@import "./cycle.css"; p{color:green}')
    await fs.writeFile(path.join(harness.fixture, 'cycle.html'), '<p>Local embed loaded</p><link rel="stylesheet" href="./cycle.css">')
    const cycle = await success('CSS_CYCLE', './cycle.html')
    assert.match(cycle.embeds[0].html, /Circular CSS import/)
    const font = (await fs.readdir(path.resolve(__dirname, '../dist/webview/assets'))).find((name) => /^KaTeX_Main-Regular.*\.woff2$/.test(name))
    assert.ok(font)
    await fs.copyFile(path.resolve(__dirname, '../dist/webview/assets', font), path.join(harness.fixture, 'font.woff2'))
    await fs.writeFile(path.join(harness.fixture, 'font.html'), '<p>Local embed loaded</p><style>@font-face{font-family:Fixture;src:url("./font.woff2")}body{font-family:Fixture}</style>')
    const fontResult = await success('FONT', './font.html')
    assert.match(fontResult.embeds[0].html, /data:font\/woff2;base64,/)
    await fs.writeFile(path.join(harness.fixture, 'srcset.html'), '<p>Local embed loaded</p><img srcset="./image.svg 1x, ./image.svg 2x">')
    const srcset = await success('SRCSET', './srcset.html')
    assert.match(srcset.embeds[0].html, /srcset="data:image\/svg\+xml;base64,/)
    assert.doesNotMatch(srcset.embeds[0].html, /\.\/image\.svg/)
    await fs.symlink(path.join(outside, 'outside.html'), path.join(harness.fixture, 'asset-link.svg'))
    await fs.writeFile(path.join(harness.fixture, 'asset-symlink.html'), '<p>Local embed loaded</p><img src="./asset-link.svg">')
    const linkedAsset = await success('ASSET_SYMLINK', './asset-symlink.html')
    assert.match(linkedAsset.embeds[0].html, /symbolic links/)
    await fs.writeFile(path.join(harness.fixture, 'oversize.svg'), 'x'.repeat(2*1024*1024+1))
    await fs.writeFile(path.join(harness.fixture, 'oversize-asset.html'), '<p>Local embed loaded</p><img src="./oversize.svg">')
    const oversize = await success('ASSET_SIZE', './oversize-asset.html')
    assert.match(oversize.embeds[0].html, /2 MiB/)
    for (let index = 0; index < 10; index++) await fs.writeFile(path.join(harness.fixture, `depth-${index}.css`), index < 9 ? `@import "./depth-${index+1}.css";` : 'p{color:green}')
    await fs.writeFile(path.join(harness.fixture, 'depth.html'), '<p>Local embed loaded</p><link rel="stylesheet" href="./depth-0.css">')
    const depth = await success('CSS_DEPTH', './depth.html')
    assert.match(depth.embeds[0].html, /8 levels/)
    await fs.writeFile(path.join(harness.fixture, 'many.html'), '<p>Local embed loaded</p>' + Array.from({length:65},(_,i)=>`<img src="./image.svg?v=${i}">`).join(''))
    await failure('RESOURCE_COUNT', './many.html', /64 local resources/)
    await fs.writeFile(path.join(harness.fixture, 'big.svg'), '<svg xmlns="http://www.w3.org/2000/svg"><!--'+ 'x'.repeat(1024*1024) +'--></svg>')
    await fs.writeFile(path.join(harness.fixture, 'repeated.html'), '<p>Local embed loaded</p>' + '<img src="./big.svg">'.repeat(20))
    await failure('OUTPUT_SIZE', './repeated.html', /16 MiB/)
    await success('PUBLIC', '/absolute.htm')
    await success('QUERY', './local.html?version=2#section')
    await failure('MISSING', './missing.html')
    await fs.writeFile(path.join(harness.fixture, 'missing.html'), html)
    await success('MISSING_RECOVERY', './missing.html')
    await failure('FILE_SYMLINK', './linked.html', /symbolic links/)
    await failure('DIRECTORY_SYMLINK', './linked-directory/outside.html', /symbolic links/)
    await failure('TRAVERSAL', '../../outside.html', /inside the workspace/)
    await failure('ENCODED_TRAVERSAL', '%2e%2e/%2e%2e/outside.html', /inside the workspace/)
    await failure('TOO_LARGE', './too-large.html', /2 MiB/)
    await failure('DIRECTORY', './directory.html', /must be a file/)
    await failure('ENCODING', './invalid-utf8.html')
    await failure('UNSUPPORTED', './unsupported.txt', /supported file type/)
    const remote = await preview('HTTP', 'http://127.0.0.1:9/forbidden')
    assert.match(remote.embeds[0].html, /must use HTTPS/)
    for (let index = 0; index < 10; index++) await harness.edit(source(`EDIT_${index}`, index % 2 ? './local.html' : '/absolute.htm'))
    await harness.wait('iframe continuous edits', frameReady('EDIT_9'))
    await harness.document.save()
    await harness.wait('iframe save', frameReady('EDIT_9'))
    harness.close(); await harness.open()
    const reopened = await harness.wait('iframe reopen', frameReady('EDIT_9'))
    assert.match(reopened.embeds[0].html, /Local embed loaded/)
    assert.deepEqual(reopened.violations, [])
    await fs.writeFile(path.join(harness.fixture, 'closing.html'), '<p>Local embed loaded</p>' + Array.from({length:64},(_,i)=>`<img src="./image.svg?v=${i}">`).join(''))
    await harness.edit(source('CLOSING', './closing.html'))
    const loading = await harness.wait('iframe close while loading', (s) => s.title === 'Embed CLOSING' && s.embeds.some((frame) => frame.busy))
    assert.match(loading.embeds[0].html, /<p role="status">Loading embedded document/, 'An iframe must show a visible loading state, not an empty document.')
    harness.close(); await harness.open()
    await harness.wait('iframe reopen after cancellation', frameReady('CLOSING'))
    await harness.edit('# Embed ISOLATION\n\n::embed[Isolation test]{src="./local.html" loading="eager"}')
    const report = await harness.wait('iframe message isolation fault injection', (s) => s.attemptedChildMessage)
    assert.equal(report.title, 'Embed ISOLATION', 'A child iframe must not replace the preview document.')
    console.log('[editor-test] PASS iframe real load, CSS/imports/fonts/srcset, bad resources/recovery, symlinks/traversal, file/resource/output limits, UTF-8, unsafe markup, HTTP rejection, edits/save/reopen, close during loading and message isolation')
  } finally { await harness.dispose(); await fs.rm(outside, { recursive: true, force: true }) }
}
